#!/usr/bin/env python3
"""Unit tests for scripts/generate_manifest.py.

`generate_manifest.py` builds the `manifest.json` the producer CI attaches to
every `lib-<sha12>` release, from the release job's downloaded artifacts. The
cases here pin the properties that are easy to break and expensive to notice:

- **Checkout-state markers never leak into a SHA.** `git submodule status`
  prefixes each line with `-` (uninitialized), `+` (mismatched) or a space
  (matching); the parser must strip the marker and keep the 40-hex SHA.
- **Stamps parse as flat text.** `#` comments and blank lines are skipped; a
  stamp lacking a required compatibility key fails the job instead of
  publishing a manifest the consumer cannot trust.
- **The manifest shape is the contract.** Exactly `tag`, `built_from_commit`,
  `platform`, `sources`, `ads_stamp`; the commit is stored verbatim (the full
  40-hex SHA); the file is indented, key-sorted JSON ending in a newline.

No network access and no third-party dependencies: the pure helpers run
against literal strings and temp files, and `main()` is driven with its git
lookup mocked. Run directly (`python scripts/test_generate_manifest.py`) or
via unittest discovery.
"""

import io
import json
import os
import sys
import tempfile
import unittest
from contextlib import redirect_stdout
from pathlib import Path
from unittest import mock

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import generate_manifest as gm  # noqa: E402

SHA = "f837ed6ff0c252b4f89ad6d480cdfd5ad25487a1"

GOOD_STAMP = (
    "# Generated by scripts/ads_standalone - what these archives may be "
    "linked against.\n"
    "qt_version=6.11.1\n"
    "cxx_standard=20\n"
    "ads_version=4.5.0\n"
    "compiler=MSVC 19.44.35211.0\n"
)


class TempDirTestCase(unittest.TestCase):
    """Base class giving every test an isolated temporary directory."""

    def setUp(self):
        self._dir = tempfile.TemporaryDirectory()
        self.addCleanup(self._dir.cleanup)
        self.tmp_path = Path(self._dir.name)


class ParseSubmoduleStatusTest(unittest.TestCase):
    def test_markers_stripped(self):
        text = (
            "-" + "a" * 40 + " src/shaderc\n"            # uninitialized
            + "+" + "b" * 40 + " src/qtadvanceddocking\n"  # mismatched
            + " " + "c" * 40 + " src/glm\n"                # matching
            + "d" * 40 + " src/stb\n"                      # no marker at all
            + "U" + "e" * 40 + " src/cereal\n"             # conflicted
            + "f" * 40 + " src/googletest (7140cd4)\n"     # describe suffix
        )
        self.assertEqual(
            gm.parse_submodule_status(text),
            {
                "src/shaderc": "a" * 40,
                "src/qtadvanceddocking": "b" * 40,
                "src/glm": "c" * 40,
                "src/stb": "d" * 40,
                "src/cereal": "e" * 40,
                "src/googletest": "f" * 40,
            },
        )

    def test_empty_input(self):
        self.assertEqual(gm.parse_submodule_status(""), {})


class ParseStampTest(unittest.TestCase):
    def test_comments_and_blanks_skipped(self):
        text = (
            "# Generated by scripts/ads_standalone\n"
            "qt_version=6.11.1\n"
            "\n"
            "   \n"
            "cxx_standard=20\n"
            "not-a-pair\n"
            "ads_version=4.5.0\n"
            "compiler=AppleClang 17.0.0.17000013\n"
        )
        self.assertEqual(
            gm.parse_stamp(text),
            {
                "qt_version": "6.11.1",
                "cxx_standard": "20",
                "ads_version": "4.5.0",
                "compiler": "AppleClang 17.0.0.17000013",
            },
        )


class CollectAdsStampsTest(TempDirTestCase):
    def _write_stamp(self, platform: str, text: str) -> None:
        path = (self.tmp_path / platform / "prebuilt" / platform
                / "qtadvanceddocking" / "build_info.txt")
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")

    def test_reads_both_platforms(self):
        self._write_stamp("windows", GOOD_STAMP)
        self._write_stamp(
            "macos", GOOD_STAMP.replace("MSVC 19.44.35211.0", "AppleClang 17.0.0")
        )
        stamps = gm.collect_ads_stamps(self.tmp_path)
        self.assertEqual(list(stamps), ["windows", "macos"])
        self.assertEqual(stamps["windows"]["qt_version"], "6.11.1")
        self.assertEqual(stamps["windows"]["cxx_standard"], "20")
        self.assertEqual(stamps["macos"]["compiler"], "AppleClang 17.0.0")

    def test_missing_stamp_file_raises(self):
        self._write_stamp("windows", GOOD_STAMP)  # macos stamp absent
        with self.assertRaises(SystemExit) as raised:
            gm.collect_ads_stamps(self.tmp_path)
        self.assertIn("missing ADS stamp for macos", str(raised.exception))

    def test_missing_required_key_raises(self):
        self._write_stamp("windows", GOOD_STAMP)
        self._write_stamp(
            "macos",
            "qt_version=6.11.1\nads_version=4.5.0\ncompiler=AppleClang\n",
        )
        with self.assertRaises(SystemExit) as raised:
            gm.collect_ads_stamps(self.tmp_path)
        self.assertIn("missing cxx_standard", str(raised.exception))


class BuildManifestTest(unittest.TestCase):
    def test_exact_keys_and_values(self):
        sources = {"src/shaderc": "1" * 40}
        stamps = {"windows": {"qt_version": "6.11.1"}, "macos": {}}
        manifest = gm.build_manifest("lib-f837ed6ff0c2", SHA, sources, stamps)
        self.assertEqual(
            manifest,
            {
                "tag": "lib-f837ed6ff0c2",
                "built_from_commit": SHA,
                "platform": ["windows", "macos"],
                "sources": sources,
                "ads_stamp": stamps,
            },
        )
        self.assertEqual(
            set(manifest),
            {"tag", "built_from_commit", "platform", "sources", "ads_stamp"},
        )


class WriteManifestTest(TempDirTestCase):
    def test_round_trips_with_trailing_newline(self):
        manifest = gm.build_manifest(
            "lib-f837ed6ff0c2", SHA, {"src/shaderc": "2" * 40}, {"windows": {}}
        )
        out = self.tmp_path / "manifest.json"
        gm.write_manifest(manifest, out)
        raw = out.read_text(encoding="utf-8")
        self.assertTrue(raw.endswith("\n"), "manifest must end with a newline")
        self.assertEqual(json.loads(raw), manifest)
        self.assertEqual(raw, json.dumps(manifest, indent=2, sort_keys=True) + "\n")


class MainTest(TempDirTestCase):
    def _write_stamps(self, artifacts: Path) -> None:
        for platform, compiler in (("windows", "MSVC 19.44.35211.0"),
                                   ("macos", "AppleClang 17.0.0")):
            path = (artifacts / platform / "prebuilt" / platform
                    / "qtadvanceddocking" / "build_info.txt")
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(
                GOOD_STAMP.replace("MSVC 19.44.35211.0", compiler),
                encoding="utf-8",
            )

    def test_main_writes_manifest_with_mocked_sources(self):
        artifacts = self.tmp_path / "artifacts"
        self._write_stamps(artifacts)
        out_dir = self.tmp_path / "release"
        out_dir.mkdir()
        out = out_dir / "manifest.json"

        with mock.patch.object(gm, "submodule_sources",
                               return_value={"src/shaderc": "3" * 40}):
            with redirect_stdout(io.StringIO()):
                rc = gm.main(["--artifacts", str(artifacts), "--out", str(out),
                              "--tag", "lib-f837ed6ff0c2", "--commit", SHA])

        self.assertEqual(rc, 0)
        manifest = json.loads(out.read_text(encoding="utf-8"))
        self.assertEqual(manifest["tag"], "lib-f837ed6ff0c2")
        self.assertEqual(manifest["built_from_commit"], SHA)
        self.assertEqual(manifest["sources"], {"src/shaderc": "3" * 40})
        self.assertEqual(set(manifest["ads_stamp"]), {"windows", "macos"})
        self.assertEqual(manifest["ads_stamp"]["macos"]["qt_version"], "6.11.1")


if __name__ == "__main__":
    unittest.main(verbosity=2)
